-- الخيارات الجانبية والأصناف الفرعية (Mohammed 2026-11-23):
-- كل خيار في مجموعة صنف بيتاخد من الخيارات الجانبية (اسمه وسعره وإتاحته بيتعدلوا من هناك بس)،
-- والخيار ممكن يكون صنف من المنيو (زي برجر جوه بوكس) عشان يتحسب في مبيعات الصنف ده.
-- أعمدة جديدة فاضية بس، فالبيانات الموجودة ما بتتغيرش.

alter table public.modifiers
  add column if not exists side_option_id text,       -- رقم الخيار الجانبي في ثوابت المنيو
  add column if not exists menu_item_id   uuid;       -- الصنف اللي الخيار ده بيمثله (من غير ربط إجباري، عشان حذف الصنف ما يمسحش الخيار)

-- كود الفئة (Mohammed 2026-11-23): كل فئة ليها 1000 رقم: الأولى 1 لـ 999، اللي بعدها 1000 لـ 1999، وهكذا.
-- العمود ده بيشيل أول رقم في نطاق الفئة (1، 1000، 2000…)، وكود الصنف بيتحفظ في sku زي ما هو.
alter table public.menu_categories
  add column if not exists code int check (code is null or code >= 0);
