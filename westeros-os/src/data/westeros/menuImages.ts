const norm = (s: string) => s.replace(/[\u{1F000}-\u{1FFFF}\u{2600}-\u{27BF}\uFE0F]/gu, "").replace(/[أإآ]/g, "ا").replace(/ى/g, "ي").replace(/ة/g, "ه").replace(/[^\p{L}\p{N}]/gu, "").toLowerCase();
const index = (m: Record<string, string>) => new Map(Object.entries(m).map(([k, v]) => [norm(k), BASE + encodeURI(v)]));
const itemIndex = index(ITEMS);
const categoryIndex = index(CATEGORIES);

